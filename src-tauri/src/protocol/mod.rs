//! The protocol: the game connection's frames read as readable messages (`docs/protocol.md`, ADR 0012). Our `.proto`
//! files in `src-tauri/protocol/` are compiled by `build.rs` into [`game`]; `message::Message` holds the messages the
//! live view reads, by their readable names, which a build's pins pair with its obfuscated ones.

#[cfg_attr(
    not(test),
    expect(
        dead_code,
        reason = "the decoder of a build's frames reads them, in the stack's next PRs"
    )
)]
mod message;

/// The messages of our `.proto` files, as `prost-build` writes them.
#[allow(
    clippy::all,
    clippy::pedantic,
    missing_debug_implementations,
    reason = "generated by prost-build: its style is not ours to lint"
)]
pub(crate) mod game {
    include!(concat!(env!("OUT_DIR"), "/d3b.game.rs"));
}
