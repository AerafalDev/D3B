//! The typed bridge to the webview: every command and event it may use. `src/bindings.ts` is generated from
//! [`builder`] by the `bindings_are_current` test, so the TypeScript side never declares an IPC type by hand.

mod character;
mod commands;
mod map;
mod relay;

pub use commands::LoadedData;
pub use relay::{start as start_relay, stop as stop_relay};

use tauri_specta::{Builder, collect_commands, collect_events};

/// Every command and event of the app.
#[must_use]
pub fn builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .commands(collect_commands![
            commands::app_info,
            relay::relay_status,
            relay::relay_restore,
            map::map_cells
        ])
        .events(collect_events![relay::RelayChanged, character::CharacterChanged])
}

#[cfg(test)]
mod tests {
    #[test]
    fn bindings_are_current() {
        super::builder()
            .export(
                specta_typescript::Typescript::default()
                    .header("// Generated by `cargo test` in src-tauri. Do not edit.\n"),
                "../src/bindings.ts",
            )
            .unwrap_or_else(|error| panic!("the TypeScript bindings could not be written: {error}"));
    }
}
