// PreToolUse on Edit, Write and NotebookEdit: refuses files that must never be written by hand or committed.
// Exit 2 refuses with the reason on stderr; any input it cannot read lets the call run (permissions stay the boundary).
import { readFileSync } from "node:fs";
import { relative } from "node:path";

const RULES: [RegExp, string][] = [
  [
    /^data\/(?!README\.md$)/,
    "data/ holds game data extracted from the client: the extractor or `bun run data:fetch` writes it",
  ],
  [/\.d3bcap$/i, "a capture holds the account's login ticket and is never written by hand"],
  [
    /(^|\/)global-metadata\.dat$|\.(bundle|binpb|assets)$/i,
    "files from the official client are never written into the repository",
  ],
  [/(^|\/)\.env(\.|$)|\.key$/i, "secrets never go in the repository"],
  [
    /^src\/bindings\.ts$/,
    "src/bindings.ts is generated by `cargo test` in src-tauri: change the Rust commands instead",
  ],
];

try {
  const input = JSON.parse(readFileSync(0, "utf8")) as { tool_input?: { file_path?: string; notebook_path?: string } };
  const path = input.tool_input?.file_path ?? input.tool_input?.notebook_path;
  if (path) {
    const root = process.env["CLAUDE_PROJECT_DIR"] ?? process.cwd();
    const inside = relative(root, path).replaceAll("\\", "/");
    for (const [pattern, reason] of RULES) {
      if (!inside.startsWith("..") && pattern.test(inside)) {
        console.error(`Refused: ${inside}: ${reason}.`);
        process.exit(2);
      }
    }
  }
} catch {
  // Unreadable input: let the call run.
}
